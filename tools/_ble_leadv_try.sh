#!/bin/sh
# Try legacy HCI name PDU. Status 12 means the controller already chose extended.
echo '=== leadv ==='
hciconfig hci0 leadv 3 2>&1 | tail -3
echo '=== set adv data ==='
# 31-byte payload: flags + complete local name CameVision-462C47
hcitool cmd 0x08 0x0008 0x1f 0x03 0x01 0x06 0x12 0x09 \
	0x43 0x61 0x6d 0x65 0x56 0x69 0x73 0x69 0x6f 0x6e \
	0x2d 0x34 0x36 0x32 0x43 0x34 0x37 \
	0x00 0x00 0x00 0x00 0x00 0x00 0x00 0x00 0x00 0x00 2>&1 | tail -8
echo '=== set scan rsp ==='
hcitool cmd 0x08 0x0009 0x1f 0x12 0x09 \
	0x43 0x61 0x6d 0x65 0x56 0x69 0x73 0x69 0x6f 0x6e \
	0x2d 0x34 0x36 0x32 0x43 0x34 0x37 \
	0x00 0x00 0x00 0x00 0x00 0x00 0x00 0x00 0x00 0x00 \
	0x00 0x00 0x00 2>&1 | tail -8
echo HCI
